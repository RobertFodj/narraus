-- Web push -tilaukset: yksi rivi per laite/selain (endpoint on laitekohtainen ja yksilöllinen).
CREATE TABLE push_subscription (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint        NOT NULL,
    endpoint   varchar(2048) NOT NULL,
    p256dh     varchar(255)  NOT NULL,
    auth       varchar(255)  NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_push_subscription_endpoint UNIQUE (endpoint),
    CONSTRAINT fk_push_subscription_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE INDEX idx_push_subscription_user ON push_subscription (user_id);
