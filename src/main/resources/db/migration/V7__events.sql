-- Kilpailut (eventit): kilpailu, osallistujat, ylläpitäjän tekemät kalojen tarkistukset ja kilpailun keskustelu.
CREATE TABLE competition_event (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(120)  NOT NULL,
    description   varchar(2000),
    starts_at     timestamp(6) with time zone NOT NULL,
    ends_at       timestamp(6) with time zone NOT NULL,
    metric        varchar(20)   NOT NULL,
    species       varchar(80),
    counted_fish  integer       NOT NULL DEFAULT 1,
    created_by_id bigint        NOT NULL,
    created_at    timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_competition_event_creator FOREIGN KEY (created_by_id) REFERENCES app_user (id),
    CONSTRAINT ck_competition_event_interval CHECK (ends_at > starts_at)
);

CREATE TABLE event_participant (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  bigint NOT NULL,
    user_id   bigint NOT NULL,
    joined_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_event_participant UNIQUE (event_id, user_id),
    CONSTRAINT fk_event_participant_event FOREIGN KEY (event_id) REFERENCES competition_event (id),
    CONSTRAINT fk_event_participant_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_event_participant_user ON event_participant (user_id);

CREATE TABLE event_fish_review (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       bigint      NOT NULL,
    post_id        bigint      NOT NULL,
    status         varchar(20) NOT NULL,
    note           varchar(500),
    reviewed_by_id bigint      NOT NULL,
    reviewed_at    timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_event_fish_review UNIQUE (event_id, post_id),
    CONSTRAINT fk_event_fish_review_event FOREIGN KEY (event_id) REFERENCES competition_event (id),
    CONSTRAINT fk_event_fish_review_post FOREIGN KEY (post_id) REFERENCES catch_post (id),
    CONSTRAINT fk_event_fish_review_reviewer FOREIGN KEY (reviewed_by_id) REFERENCES app_user (id)
);
CREATE INDEX idx_event_fish_review_post ON event_fish_review (post_id);

CREATE TABLE event_message (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  bigint        NOT NULL,
    sender_id bigint        NOT NULL,
    text      varchar(1000) NOT NULL,
    sent_at   timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_event_message_event FOREIGN KEY (event_id) REFERENCES competition_event (id),
    CONSTRAINT fk_event_message_sender FOREIGN KEY (sender_id) REFERENCES app_user (id)
);
CREATE INDEX idx_event_message_event ON event_message (event_id, sent_at);
CREATE INDEX idx_event_message_sender ON event_message (sender_id);
