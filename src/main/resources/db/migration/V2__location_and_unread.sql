-- Milloin käyttäjä on viimeksi lukenut tietyn keskustelun.
CREATE TABLE conversation_read (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL,
    user_id         bigint NOT NULL,
    last_read_at    timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_conversation_read UNIQUE (conversation_id, user_id),
    CONSTRAINT fk_conversation_read_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_conversation_read_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
