-- Narraus-viestit: ylläpitäjän lähettämät viestit. Vastaanottaja näkee lähettäjäksi "Narraus" (ei ylläpitäjän
-- nimeä); sent_by_id on vain jäljitettävyyttä varten. Yksi rivi per vastaanottaja.
CREATE TABLE system_message (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint        NOT NULL,
    sent_by_id   bigint,
    text         varchar(1000) NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL DEFAULT now(),
    read_at      timestamp(6) with time zone,
    CONSTRAINT fk_system_message_recipient FOREIGN KEY (recipient_id) REFERENCES app_user (id),
    CONSTRAINT fk_system_message_sender FOREIGN KEY (sent_by_id) REFERENCES app_user (id) ON DELETE SET NULL
);

CREATE INDEX idx_system_message_recipient ON system_message (recipient_id, created_at);
