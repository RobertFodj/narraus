-- Sovelluksen sisäiset ilmoitukset (kellokuvake): uusi seuraaja, tykkäys, uusi kilpailu.
-- Narraus-viestit (system_message) näytetään samassa listassa, mutta ne säilyvät omassa taulussaan.
CREATE TABLE app_notification (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint      NOT NULL REFERENCES app_user (id),
    actor_id     bigint      REFERENCES app_user (id),
    type         varchar(20) NOT NULL,
    target_id    bigint,
    label        varchar(200),
    created_at   timestamptz NOT NULL DEFAULT now(),
    read_at      timestamptz
);
CREATE INDEX idx_app_notification_recipient ON app_notification (recipient_id, created_at DESC);
