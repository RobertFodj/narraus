-- Ylläpitäjän päätökset (toisen käyttäjän julkaisun poisto/muokkaus) ja käyttäjän valitukset niistä.
CREATE TABLE moderation_action (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id   bigint       NOT NULL REFERENCES app_user (id),
    actor_id    bigint       NOT NULL REFERENCES app_user (id),
    kind        varchar(20)  NOT NULL,
    species     varchar(255),
    description varchar(2000),
    reason      varchar(500),
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_moderation_action_author ON moderation_action (author_id);

CREATE TABLE moderation_appeal (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id  bigint        NOT NULL REFERENCES moderation_action (id),
    author_id  bigint        NOT NULL REFERENCES app_user (id),
    text       varchar(2000) NOT NULL,
    created_at timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX idx_moderation_appeal_action ON moderation_appeal (action_id);
