-- Narrauksen alkuperäinen skeema (vastaa Hibernaten aiemmin luomaa rakennetta).
-- Älä muokkaa tätä tiedostoa julkaisun jälkeen: tee muutokset uusina V2__..., V3__... -migraatioina.

CREATE TABLE app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    display_name  varchar(255) NOT NULL,
    CONSTRAINT uq_app_user_username UNIQUE (username)
);

CREATE TABLE catch_post (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id   bigint       NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    species     varchar(255) NOT NULL,
    weight_kg   double precision,
    length_cm   double precision,
    girth_cm    double precision,
    location    varchar(255),
    description varchar(2000),
    photo_file  varchar(255),
    CONSTRAINT fk_catch_post_author FOREIGN KEY (author_id) REFERENCES app_user (id)
);

CREATE TABLE post_like (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT uq_post_like_post_user UNIQUE (post_id, user_id),
    CONSTRAINT fk_post_like_post FOREIGN KEY (post_id) REFERENCES catch_post (id),
    CONSTRAINT fk_post_like_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE follow (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id bigint NOT NULL,
    followed_id bigint NOT NULL,
    CONSTRAINT uq_follow_follower_followed UNIQUE (follower_id, followed_id),
    CONSTRAINT fk_follow_follower FOREIGN KEY (follower_id) REFERENCES app_user (id),
    CONSTRAINT fk_follow_followed FOREIGN KEY (followed_id) REFERENCES app_user (id)
);

CREATE TABLE conversation (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(255),
    group_chat    boolean NOT NULL,
    last_activity timestamp(6) with time zone
);

CREATE TABLE conversation_participants (
    conversation_id bigint NOT NULL,
    participants_id bigint NOT NULL,
    PRIMARY KEY (conversation_id, participants_id),
    CONSTRAINT fk_conv_part_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_conv_part_user FOREIGN KEY (participants_id) REFERENCES app_user (id)
);

CREATE TABLE chat_message (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint       NOT NULL,
    sender_id       bigint       NOT NULL,
    sent_at         timestamp(6) with time zone NOT NULL,
    text            varchar(2000) NOT NULL,
    CONSTRAINT fk_chat_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_chat_message_sender FOREIGN KEY (sender_id) REFERENCES app_user (id)
);
