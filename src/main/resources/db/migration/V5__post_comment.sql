-- Kommentit saaliisiin.
CREATE TABLE post_comment (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    bigint        NOT NULL,
    author_id  bigint        NOT NULL,
    text       varchar(1000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_post_comment_post FOREIGN KEY (post_id) REFERENCES catch_post (id),
    CONSTRAINT fk_post_comment_author FOREIGN KEY (author_id) REFERENCES app_user (id)
);

CREATE INDEX idx_post_comment_post ON post_comment (post_id, created_at);
CREATE INDEX idx_post_comment_author ON post_comment (author_id);
